import hashlib
import hmac
import os
import re
import secrets
import sqlite3
import time
from contextlib import contextmanager
from pathlib import Path

from flask import Flask, jsonify, redirect, request, send_from_directory
from werkzeug.middleware.proxy_fix import ProxyFix


ROOT_DIR = Path(__file__).resolve().parent
PASSWORD_ITERATIONS = 310_000
SESSION_LIFETIME_SECONDS = 12 * 60 * 60
SESSION_COOKIE_NAME = "capico_session"
USERNAME_PATTERN = re.compile(r"^[a-z0-9._-]{3,24}$")
PHONE_PATTERN = re.compile(r"^\+?[0-9]{7,15}$")
SESSION_TOKEN_PATTERN = re.compile(r"^[A-Za-z0-9_-]{32,64}$")


class DatabaseConnection:
    def __init__(self, connection, is_postgres: bool):
        self.connection = connection
        self.is_postgres = is_postgres

    def execute(self, query: str, values: tuple = ()):
        if self.is_postgres:
            query = query.replace("?", "%s")
        return self.connection.execute(query, values)


class Database:
    def __init__(self, database_url: str):
        self.database_url = database_url
        self.is_postgres = database_url.startswith(("postgres://", "postgresql://"))
        self.sqlite_path = None
        self.integrity_error_type = sqlite3.IntegrityError

        if self.is_postgres:
            import psycopg

            self.integrity_error_type = psycopg.IntegrityError
            if database_url.startswith("postgres://"):
                self.database_url = database_url.replace("postgres://", "postgresql://", 1)
        else:
            prefix = "sqlite:///"
            if not database_url.startswith(prefix):
                raise ValueError("DATABASE_URL must use PostgreSQL or SQLite.")
            self.sqlite_path = Path(database_url[len(prefix):])
            self.sqlite_path.parent.mkdir(parents=True, exist_ok=True)

    @contextmanager
    def connect(self):
        if self.is_postgres:
            import psycopg
            from psycopg.rows import dict_row

            connection = psycopg.connect(self.database_url, row_factory=dict_row)
        else:
            connection = sqlite3.connect(str(self.sqlite_path), timeout=10)
            connection.row_factory = sqlite3.Row
            connection.execute("PRAGMA foreign_keys = ON")

        try:
            yield DatabaseConnection(connection, self.is_postgres)
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()

    def initialize(self):
        with self.connect() as database:
            if self.is_postgres:
                database.execute(
                    """
                    CREATE TABLE IF NOT EXISTS users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username VARCHAR(24) NOT NULL UNIQUE,
                        phone VARCHAR(16) NOT NULL UNIQUE,
                        password_salt VARCHAR(32) NOT NULL,
                        password_hash VARCHAR(64) NOT NULL,
                        created_at BIGINT NOT NULL
                    )
                    """
                )
                database.execute(
                    """
                    CREATE TABLE IF NOT EXISTS login_sessions (
                        token_hash VARCHAR(64) PRIMARY KEY,
                        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                        expires_at BIGINT NOT NULL
                    )
                    """
                )
            else:
                database.execute(
                    """
                    CREATE TABLE IF NOT EXISTS users (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        username VARCHAR(24) NOT NULL UNIQUE,
                        phone VARCHAR(16) NOT NULL UNIQUE,
                        password_salt VARCHAR(32) NOT NULL,
                        password_hash VARCHAR(64) NOT NULL,
                        created_at BIGINT NOT NULL
                    )
                    """
                )
                database.execute(
                    """
                    CREATE TABLE IF NOT EXISTS login_sessions (
                        token_hash VARCHAR(64) PRIMARY KEY,
                        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                        expires_at BIGINT NOT NULL
                    )
                    """
                )
            database.execute(
                "CREATE INDEX IF NOT EXISTS ix_login_sessions_user_id ON login_sessions(user_id)"
            )
            database.execute(
                "CREATE INDEX IF NOT EXISTS ix_login_sessions_expires_at ON login_sessions(expires_at)"
            )


def password_digest(password: str, salt: bytes) -> str:
    return hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), salt, PASSWORD_ITERATIONS
    ).hex()


def create_app(database_url: str | None = None, cookie_secure: bool | None = None) -> Flask:
    app = Flask(__name__, static_folder=None)
    app.config["MAX_CONTENT_LENGTH"] = 4096
    app.wsgi_app = ProxyFix(app.wsgi_app, x_for=1, x_proto=1, x_host=1)

    configured_url = database_url or os.environ.get("DATABASE_URL")
    if not configured_url:
        if os.environ.get("RENDER"):
            raise RuntimeError("DATABASE_URL must be set on the deployed service.")
        database_path = Path(
            os.environ.get("CAPICO_DATABASE_PATH", ROOT_DIR / "data" / "capico.sqlite3")
        ).resolve()
        configured_url = "sqlite:///" + database_path.as_posix()

    database = Database(configured_url)
    database.initialize()
    app.extensions["capico_database"] = database

    if cookie_secure is None:
        cookie_secure = os.environ.get(
            "COOKIE_SECURE", "true" if os.environ.get("DATABASE_URL") else "false"
        ).lower() == "true"

    def login_response(username: str, token: str, status: int = 200):
        response = jsonify({"username": username})
        response.status_code = status
        response.headers["Cache-Control"] = "no-store"
        response.set_cookie(
            SESSION_COOKIE_NAME,
            token,
            max_age=SESSION_LIFETIME_SECONDS,
            httponly=True,
            secure=cookie_secure,
            samesite="Strict",
            path="/api",
        )
        return response

    def read_payload():
        payload = request.get_json(silent=True)
        return payload if isinstance(payload, dict) else None

    def token_digest(token: str | None):
        if not token or not SESSION_TOKEN_PATTERN.fullmatch(token):
            return None
        return hashlib.sha256(token.encode("ascii")).hexdigest()

    @app.get("/api/health")
    def health():
        with database.connect() as connection:
            connection.execute("SELECT 1")
        return jsonify({"status": "ok"})

    @app.post("/api/register")
    def register():
        payload = read_payload()
        if payload is None:
            return jsonify({"error": "So‘rov ma’lumotlari noto‘g‘ri."}), 400

        username = payload.get("username")
        phone_input = payload.get("phone")
        password = payload.get("password")
        if not all(isinstance(value, str) for value in (username, phone_input, password)):
            return jsonify({"error": "Telefon, login va parolni kiriting."}), 400

        username = username.strip().lower()
        phone_input = re.sub(r"[\s()-]", "", phone_input)
        if not USERNAME_PATTERN.fullmatch(username):
            return jsonify({"error": "Login 3–24 belgi bo‘lishi kerak."}), 400
        if not PHONE_PATTERN.fullmatch(phone_input):
            return jsonify({"error": "Telefon raqamini xalqaro formatda kiriting."}), 400
        phone = "+" + re.sub(r"\D", "", phone_input)
        if len(password) < 7 or len(password) > 128:
            return jsonify({"error": "Parol 7–128 belgidan iborat bo‘lishi kerak."}), 400

        salt = secrets.token_bytes(16)
        token = secrets.token_urlsafe(32)
        now = int(time.time())
        try:
            with database.connect() as connection:
                existing_user = connection.execute(
                    "SELECT id FROM users WHERE username = ? OR phone = ? LIMIT 1",
                    (username, phone),
                ).fetchone()
                if existing_user:
                    return jsonify({"error": "Bu login yoki telefon raqami band."}), 409

                user = connection.execute(
                    """
                    INSERT INTO users (username, phone, password_salt, password_hash, created_at)
                    VALUES (?, ?, ?, ?, ?)
                    RETURNING id
                    """,
                    (username, phone, salt.hex(), password_digest(password, salt), now),
                ).fetchone()
                connection.execute(
                    "INSERT INTO login_sessions (token_hash, user_id, expires_at) VALUES (?, ?, ?)",
                    (
                        hashlib.sha256(token.encode("ascii")).hexdigest(),
                        user["id"],
                        now + SESSION_LIFETIME_SECONDS,
                    ),
                )
        except database.integrity_error_type:
            return jsonify({"error": "Bu login yoki telefon raqami band."}), 409
        return login_response(username, token, 201)

    @app.post("/api/login")
    def login():
        payload = read_payload()
        if payload is None:
            return jsonify({"error": "So‘rov ma’lumotlari noto‘g‘ri."}), 400

        username = payload.get("username")
        password = payload.get("password")
        if not isinstance(username, str) or not isinstance(password, str):
            return jsonify({"error": "Login yoki parol noto‘g‘ri."}), 401
        username = username.strip().lower()
        if not USERNAME_PATTERN.fullmatch(username) or len(password) > 128:
            return jsonify({"error": "Login yoki parol noto‘g‘ri."}), 401

        token = secrets.token_urlsafe(32)
        now = int(time.time())
        with database.connect() as connection:
            user = connection.execute(
                "SELECT id, username, password_salt, password_hash FROM users WHERE username = ?",
                (username,),
            ).fetchone()
            if user is None:
                return jsonify({"error": "Login yoki parol noto‘g‘ri."}), 401
            actual_hash = password_digest(password, bytes.fromhex(user["password_salt"]))
            if not hmac.compare_digest(actual_hash, user["password_hash"]):
                return jsonify({"error": "Login yoki parol noto‘g‘ri."}), 401

            connection.execute(
                "DELETE FROM login_sessions WHERE expires_at <= ?", (now,)
            )
            connection.execute(
                "INSERT INTO login_sessions (token_hash, user_id, expires_at) VALUES (?, ?, ?)",
                (
                    hashlib.sha256(token.encode("ascii")).hexdigest(),
                    user["id"],
                    now + SESSION_LIFETIME_SECONDS,
                ),
            )
        return login_response(user["username"], token)

    @app.get("/api/me")
    def me():
        token_hash = token_digest(request.cookies.get(SESSION_COOKIE_NAME))
        if not token_hash:
            return jsonify({"error": "Hisobga kiring."}), 401
        now = int(time.time())
        with database.connect() as connection:
            user = connection.execute(
                """
                SELECT users.username
                FROM login_sessions
                JOIN users ON users.id = login_sessions.user_id
                WHERE login_sessions.token_hash = ? AND login_sessions.expires_at > ?
                """,
                (token_hash, now),
            ).fetchone()
        if user is None:
            return jsonify({"error": "Hisobga kiring."}), 401
        return jsonify({"username": user["username"]})

    @app.post("/api/logout")
    def logout():
        token_hash = token_digest(request.cookies.get(SESSION_COOKIE_NAME))
        if token_hash:
            with database.connect() as connection:
                connection.execute(
                    "DELETE FROM login_sessions WHERE token_hash = ?", (token_hash,)
                )
        response = jsonify({"status": "ok"})
        response.delete_cookie(
            SESSION_COOKIE_NAME,
            httponly=True,
            secure=cookie_secure,
            samesite="Strict",
            path="/api",
        )
        response.headers["Cache-Control"] = "no-store"
        return response

    @app.get("/")
    def root():
        if (ROOT_DIR / "index.html").is_file():
            return send_from_directory(ROOT_DIR, "index.html")
        return redirect("/kod/cc.html")

    @app.get("/kod/<path:asset>")
    def kod_asset(asset):
        return send_from_directory(ROOT_DIR / "kod", asset)

    @app.get("/img/<path:asset>")
    def image_asset(asset):
        return send_from_directory(ROOT_DIR / "img", asset)

    @app.errorhandler(413)
    def request_too_large(_error):
        return jsonify({"error": "So‘rov hajmi juda katta."}), 413

    @app.errorhandler(404)
    def not_found(_error):
        if request.path.startswith("/api/"):
            return jsonify({"error": "API manzili topilmadi."}), 404
        if (ROOT_DIR / "404.html").is_file():
            return send_from_directory(ROOT_DIR, "404.html"), 404
        return "Sahifa topilmadi.", 404

    return app


app = create_app()


if __name__ == "__main__":
    app.run(
        host=os.environ.get("HOST", "127.0.0.1"),
        port=int(os.environ.get("PORT", "8000")),
    )

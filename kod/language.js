const languageNames = { en: 'English', uz: 'O‘zbekcha', ru: 'Русский' };
const languageStorageKey = 'capico-language';
const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function translateText(value, language) {
  const selectedLanguage = language || document.documentElement.lang || 'en';
  return selectedLanguage === 'en'
    ? value
    : (translations[selectedLanguage][value] || value);
}

function applyTranslations(language) {
  const selectedLanguage = language || localStorage.getItem(languageStorageKey) || 'en';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;

  while ((node = walker.nextNode())) {
    if (!node.nodeValue.trim() || node.parentElement.closest('script, style, .language-options')) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);

    const source = originalText.get(node);
    const leading = source.match(/^\s*/)[0];
    const trailing = source.match(/\s*$/)[0];
    const key = source.trim().replace(/\s+/g, ' ');
    node.nodeValue = leading + translateText(key, selectedLanguage) + trailing;
  }

  document.querySelectorAll('[aria-label], [placeholder], [alt], [title]').forEach(function (element) {
    ['aria-label', 'placeholder', 'alt', 'title'].forEach(function (attribute) {
      if (!element.hasAttribute(attribute)) return;
      let values = originalAttributes.get(element);
      if (!values) {
        values = {};
        originalAttributes.set(element, values);
      }
      if (!(attribute in values)) values[attribute] = element.getAttribute(attribute);
      element.setAttribute(attribute, translateText(values[attribute], selectedLanguage));
    });
  });

  document.documentElement.lang = selectedLanguage;
  const pageTitle = document.querySelector('title');
  if (pageTitle) {
    if (!originalText.has(pageTitle)) originalText.set(pageTitle, pageTitle.textContent);
    pageTitle.textContent = translateText(originalText.get(pageTitle), selectedLanguage);
  }

  const currentLanguage = document.getElementById('currentLanguage');
  if (currentLanguage) currentLanguage.textContent = selectedLanguage;
  const languageButton = document.querySelector('.lang-selector');
  if (languageButton) languageButton.setAttribute('aria-label', 'Language: ' + languageNames[selectedLanguage]);
  document.querySelectorAll('.language-option').forEach(function (option) {
    const active = option.textContent.trim() === selectedLanguage;
    option.classList.toggle('active', active);
    option.setAttribute('aria-pressed', String(active));
  });

  if (typeof selectFeature === 'function' && typeof activeFeatureIndex !== 'undefined') {
    selectFeature(activeFeatureIndex);
  }
}

function toggleLanguages(forceOpen) {
  const options = document.querySelector('.language-options');
  const button = document.querySelector('.lang-selector');
  if (!options || !button) return;
  const open = typeof forceOpen === 'boolean' ? forceOpen : options.hidden;
  options.hidden = !open;
  button.setAttribute('aria-expanded', String(open));
}

function selectLanguage(language) {
  if (!['en', 'uz', 'ru'].includes(language)) return;
  localStorage.setItem(languageStorageKey, language);
  applyTranslations(language);
  toggleLanguages(false);
}

window.translateText = translateText;
window.applyTranslations = applyTranslations;

document.addEventListener('click', function (event) {
  if (!event.target.closest('.language-picker')) toggleLanguages(false);
});

document.addEventListener('keydown', function (event) {
  if (event.key === 'Escape') toggleLanguages(false);
});

